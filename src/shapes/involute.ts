// Gear tooth outlines: involute (spur gears) and cycloidal (clock and watch trains).
//
// The involute construction follows BOSL2 `gears.scad` (`_gear_tooth_profile`, `_base_radius`,
// `_dedendum`, `_invol`; BSD-2-Clause, Copyright (c) 2017-2019, Revar Desmera; see CREDITS.md),
// itself inspired by Leemon Baird's public-domain parametric involute spur gear. Ported and
// simplified: no backlash, profile shift, helix or undercut; the flank below the base circle is
// radial. The radii are the standard full-depth system: addendum = module, dedendum = 1.25 module
// (BOSL2's default clearance of module / 4), base radius = pitch radius x cos(pressure angle).
// The cycloidal profile is derived from the textbook epicycloid; it is not ported from anywhere.

import type { Vec2 } from '../math/vec';

export interface GearOptions {
  teeth: number;
  /** Pitch diameter / teeth. The pitch radius is `module * teeth / 2`. */
  module: number;
}

export interface InvoluteGearOptions extends GearOptions {
  /** Default 20. */
  pressureAngleDeg?: number;
}

export interface CycloidalGearOptions extends GearOptions {
  /** Radius of the generating circle rolled on the pitch circle for the tooth tips. Default 1.5 module. */
  rollingRadius?: number;
}

const FLANK_STEPS = 8; // segments per tooth flank
const TIP_STEPS = 4; // segments across a tooth tip
const ROOT_STEPS = 4; // segments across a root gap

/** Flank samples of one tooth: radius and the half-angle of the tooth at that radius, root to tip. */
type Flank = [radius: number, halfAngle: number][];

const polar = (r: number, a: number): Vec2 => [r * Math.cos(a), r * Math.sin(a)];

function checkOptions({ teeth, module }: GearOptions): void {
  if (!Number.isInteger(teeth) || teeth < 3) throw new RangeError(`teeth must be an integer >= 3, got ${teeth}`);
  if (!(module > 0)) throw new RangeError(`module must be positive, got ${module}`);
}

/** Lay `teeth` copies of a tooth (given by its flank, symmetric about its centre line) around a closed CCW outline. */
function layOut(teeth: number, flank: Flank, rootRadius: number): Vec2[] {
  const step = (2 * Math.PI) / teeth;
  const rootHalf = flank[0][1];
  const [tipRadius, tipHalf] = flank[flank.length - 1];
  const out: Vec2[] = [];
  for (let k = 0; k < teeth; k++) {
    const c = k * step;
    for (const [r, h] of flank) out.push(polar(r, c - h));
    for (let j = 1; j < TIP_STEPS; j++) out.push(polar(tipRadius, c - tipHalf + (2 * tipHalf * j) / TIP_STEPS));
    for (let i = flank.length - 1; i >= 0; i--) out.push(polar(flank[i][0], c + flank[i][1]));
    const gap = step - 2 * rootHalf;
    for (let j = 1; j < ROOT_STEPS; j++) out.push(polar(rootRadius, c + rootHalf + (gap * j) / ROOT_STEPS));
  }
  return out;
}

/** Smallest x in [lo, hi] where the monotone predicate turns true (hi if it never does). */
function bisect(lo: number, hi: number, pred: (x: number) => boolean): number {
  if (!pred(hi)) return hi;
  for (let i = 0; i < 60; i++) {
    const mid = (lo + hi) / 2;
    if (pred(mid)) hi = mid;
    else lo = mid;
  }
  return hi;
}

/** Involute function: the polar angle swept by an involute at pressure angle `a` (radians). */
const inv = (a: number): number => Math.tan(a) - a;

/**
 * Closed counter-clockwise outline of an involute spur gear centred on the origin, with a tooth
 * centred on +x. Tooth thickness at the pitch circle is half the circular pitch, so two gears of the
 * same module mesh at a centre distance equal to the sum of their pitch radii.
 */
export function involuteGear(opts: InvoluteGearOptions): Vec2[] {
  checkOptions(opts);
  const { teeth, module } = opts;
  const alpha = ((opts.pressureAngleDeg ?? 20) * Math.PI) / 180;
  const pitch = (module * teeth) / 2;
  const base = pitch * Math.cos(alpha);
  const root = pitch - 1.25 * module;
  // Half-angle of the tooth at radius r >= base: the involute's polar angle measured from the pitch point.
  const half = (r: number): number => Math.PI / (2 * teeth) + inv(alpha) - inv(Math.acos(Math.min(1, base / r)));
  // Few teeth or a large pressure angle can point the tooth below the addendum circle: stop the
  // flanks just short of meeting, as BOSL2 does.
  const minTipHalf = 0.04 * (Math.PI / (2 * teeth));
  const tip = bisect(pitch, pitch + module, (r) => half(r) <= minTipHalf);
  const start = Math.max(root, base);
  const flank: Flank = [];
  if (root < base) flank.push([root, half(base)]); // radial flank below the base circle
  for (let i = 0; i <= FLANK_STEPS; i++) {
    const r = start + ((tip - start) * i) / FLANK_STEPS;
    flank.push([r, half(r)]);
  }
  return layOut(teeth, flank, root);
}

/**
 * Closed counter-clockwise outline of a cycloidal gear (horological style): epicycloidal tips
 * generated by rolling a circle of `rollingRadius` on the pitch circle, radial flanks below the
 * pitch circle, addendum up to 1.4 module (lower where the tips meet in an ogive), dedendum 1.6 module.
 */
export function cycloidalGear(opts: CycloidalGearOptions): Vec2[] {
  checkOptions(opts);
  const { teeth, module } = opts;
  const R = (module * teeth) / 2;
  const rho = opts.rollingRadius ?? 1.5 * module;
  if (!(rho > 0)) throw new RangeError(`rollingRadius must be positive, got ${rho}`);
  const pitchHalf = Math.PI / (2 * teeth);
  const minTipHalf = 0.04 * pitchHalf;
  const kk = (R + rho) / rho;
  // Epicycloid traced from the pitch point by a circle rolling outside the pitch circle.
  const epi = (t: number): [number, number] => {
    const x = (R + rho) * Math.cos(t) - rho * Math.cos(kk * t);
    const y = (R + rho) * Math.sin(t) - rho * Math.sin(kk * t);
    return [Math.hypot(x, y), Math.atan2(y, x)];
  };
  // Radius and polar angle both grow monotonically up to the first cusp at t = pi / kk.
  const tEnd = bisect(0, Math.PI / kk, (t) => {
    const [r, phi] = epi(t);
    return r >= R + 1.4 * module || pitchHalf - phi <= minTipHalf;
  });
  const flank: Flank = [[R - 1.6 * module, pitchHalf]];
  for (let i = 0; i <= FLANK_STEPS; i++) {
    const [r, phi] = epi((tEnd * i) / FLANK_STEPS);
    flank.push([r, pitchHalf - phi]);
  }
  return layOut(teeth, flank, R - 1.6 * module);
}
